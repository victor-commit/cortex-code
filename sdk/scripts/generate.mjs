// Generates the typed SDK surface from the committed OpenAPI snapshot (openapi.json).
//
// The snapshot is the canonical contract: it is captured verbatim from the running
// `cortex serve` /openapi.json document, so the generated schema interfaces, the operation
// table, and the runtime required-field validators always track the served document. Run with
// `npm run generate` after refreshing openapi.json. Output is deterministic (the snapshot keys
// are already sorted by the server), so regeneration is reproducible and diffable in tests.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const doc = JSON.parse(readFileSync(join(root, "openapi.json"), "utf8"));

const schemas = doc.components?.schemas ?? {};
const paths = doc.paths ?? {};
const eventFamilies = doc["x-event-families"] ?? [];

const HEADER = "// GENERATED by scripts/generate.mjs from openapi.json. Do not edit by hand.\n";
const METHODS = ["get", "post", "put", "patch", "delete"];

function refName(ref) {
  return ref.replace("#/components/schemas/", "");
}
function safeKey(key) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}
function wrap(type) {
  return /[|]/.test(type) ? `(${type})` : type;
}
function primitive(type, schema) {
  switch (type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return `${wrap(tsType(schema.items ?? {}))}[]`;
    case "object":
      return objectType(schema);
    default:
      return "unknown";
  }
}
function tsType(schema) {
  if (!schema || typeof schema !== "object") return "unknown";
  if (schema.$ref) return refName(schema.$ref);
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (Array.isArray(schema.enum)) {
    return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  }
  if (Array.isArray(schema.type)) {
    return schema.type.map((type) => (type === "null" ? "null" : primitive(type, schema))).join(" | ");
  }
  if (schema.type === "array") return `${wrap(tsType(schema.items ?? {}))}[]`;
  if (schema.type === "object" || (!schema.type && schema.properties)) return objectType(schema);
  if (schema.type) return primitive(schema.type, schema);
  return "unknown";
}
function objectType(schema) {
  const props = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const lines = [];
  for (const [key, value] of Object.entries(props)) {
    const optional = required.has(key) ? "" : "?";
    lines.push(`${safeKey(key)}${optional}: ${tsType(value)};`);
  }
  const extra = schema.additionalProperties;
  if (extra === true) lines.push("[key: string]: unknown;");
  else if (extra && typeof extra === "object") lines.push(`[key: string]: ${tsType(extra)};`);
  if (lines.length === 0) return "Record<string, unknown>";
  return `{ ${lines.join(" ")} }`;
}
function declare(name, schema) {
  const isObject = schema.type === "object" || (!schema.type && schema.properties && !schema.enum);
  if (isObject) {
    const body = objectType(schema);
    if (body.startsWith("{")) return `export interface ${name} ${body}\n`;
    return `export type ${name} = ${body};\n`;
  }
  return `export type ${name} = ${tsType(schema)};\n`;
}

// --- src/gen/types.ts ---------------------------------------------------------
let types = HEADER + "\n";
for (const name of Object.keys(schemas)) {
  types += declare(name, schemas[name]);
}
types += "\n";
types += `export type CortexEventKind =\n  | ${eventFamilies.map((kind) => JSON.stringify(kind)).join("\n  | ")};\n`;
types += "\n";
const operationIds = [];
for (const path of Object.keys(paths)) {
  for (const method of METHODS) {
    const op = paths[path]?.[method];
    if (op?.operationId) operationIds.push(op.operationId);
  }
}
operationIds.sort();
types += `export type OperationId =\n  | ${operationIds.map((id) => JSON.stringify(id)).join("\n  | ")};\n`;
writeFileSync(join(root, "src", "gen", "types.ts"), types);

// --- src/gen/operations.ts ----------------------------------------------------
function pathParams(path) {
  return [...path.matchAll(/\{([^}]+)\}/g)].map((match) => match[1]);
}
let ops = HEADER + 'import type { OperationId } from "./types.ts";\n\n';
ops += "export interface OperationMeta {\n";
ops += "  readonly method: \"get\" | \"post\" | \"put\" | \"patch\" | \"delete\";\n";
ops += "  readonly path: string;\n";
ops += "  readonly pathParams: readonly string[];\n";
ops += "  readonly successStatus: number;\n";
ops += "}\n\n";
ops += "export const OPERATIONS: Record<OperationId, OperationMeta> = {\n";
const entries = [];
for (const path of Object.keys(paths)) {
  for (const method of METHODS) {
    const op = paths[path]?.[method];
    if (!op?.operationId) continue;
    const success = Object.keys(op.responses ?? {})
      .map((code) => Number.parseInt(code, 10))
      .filter((code) => code >= 200 && code < 300)
      .sort((a, b) => a - b)[0] ?? 200;
    entries.push({ id: op.operationId, method, path, params: pathParams(path), success });
  }
}
entries.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
for (const entry of entries) {
  const params = entry.params.map((name) => JSON.stringify(name)).join(", ");
  ops += `  ${safeKey(entry.id)}: { method: ${JSON.stringify(entry.method)}, path: ${JSON.stringify(entry.path)}, pathParams: [${params}], successStatus: ${entry.success} },\n`;
}
ops += "};\n";
writeFileSync(join(root, "src", "gen", "operations.ts"), ops);

// --- src/gen/schemas.ts -------------------------------------------------------
let schemaModule = HEADER + "\n";
schemaModule += "export const OPENAPI_SCHEMA_NAMES: readonly string[] = [\n";
for (const name of Object.keys(schemas)) schemaModule += `  ${JSON.stringify(name)},\n`;
schemaModule += "];\n\n";
schemaModule += "export const REQUIRED_FIELDS: Record<string, readonly string[]> = {\n";
for (const name of Object.keys(schemas)) {
  const required = schemas[name]?.required ?? [];
  schemaModule += `  ${JSON.stringify(name)}: [${required.map((field) => JSON.stringify(field)).join(", ")}],\n`;
}
schemaModule += "};\n\n";
schemaModule += "export const EVENT_FAMILIES: readonly string[] = [\n";
for (const kind of eventFamilies) schemaModule += `  ${JSON.stringify(kind)},\n`;
schemaModule += "];\n";
writeFileSync(join(root, "src", "gen", "schemas.ts"), schemaModule);

console.log(
  `generated ${Object.keys(schemas).length} schemas, ${entries.length} operations, ${eventFamilies.length} event families`,
);
